// Re-sign the captured output/MMR roots for Phase 1 using the registered projections.
// Synthetic conformance fixtures, not a capture from a running Phase 1 Worker.
// Usage: node test/e2e/fixtures/gen/phase1-output.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { sha256 } from '@noble/hashes/sha256';
import { secp256k1 } from '@noble/curves/secp256k1';
const u64 = n => { const b = Buffer.alloc(8); b.writeBigUInt64BE(BigInt(n)); return b; };
const u32 = n => { const b = Buffer.alloc(4); b.writeUInt32BE(n); return b; };
const frame = (...fields) => Buffer.concat(fields.flatMap(b => [u64(b.length), b]));
const hash = (domain, ...fields) => sha256(frame(Buffer.from(domain), ...fields));
const raw = h => Buffer.from(h, 'hex');
const sign = digest => Buffer.from(secp256k1.sign(digest, raw('31'.repeat(32)), { lowS: true, prehash: false }).toCompactRawBytes()).toString('hex');
for (const name of ['output-stream.json', 'worker-reference-stream.json']) {
  const path = new URL(`../${name}`, import.meta.url);
  const data = JSON.parse(readFileSync(path, 'utf8'));
  data.note = 'Synthetic Phase 1 signatures over captured Worker output/MMR roots; regenerated by gen/phase1-output.mjs. Not a Phase 1 live-network capture.';
  if (name === 'output-stream.json') data.task_hash = '53bfd0b61fbb4cc7a9727b2090b29a0d1198eb5dc4c5e1bf65e245036236f0e1';
  data.dispatch_ticket_hash = '33'.repeat(32);
  const base = [Buffer.from(data.chain_id), raw(data.task_hash), raw(data.dispatch_ticket_hash)];
  for (const f of data.frames) f.sig_hex = sign(hash('TRUEOPEN_OUTPUT_CHUNK_V1', ...base, u64(f.seq), raw(f.root_hex)));
  const f = data.fin;
  f.sig_hex = sign(hash('TRUEOPEN_OUTPUT_FIN_V1', ...base, u64(f.final_seq), raw(f.root_hex), u32(f.finish_reason)));
  writeFileSync(path, JSON.stringify(data, null, 2) + '\n');
}
